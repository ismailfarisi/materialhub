export const AppDataSource = new DataSource({
  type: "postgres",
  host: config.database.host,
  port: config.database.port,
  username: config.database.username,
  password: config.database.password,
  database: config.database.database,
  // RDS PostgreSQL forces SSL (rds.force_ssl); a containerized Postgres
  // (Netcup staging, local dev) does not — pg errors with "server does not
  // support SSL connections" if we request it. DB_SSL=false explicitly opts
  // out even in production. Default behaviour is unchanged (SSL on in
  // production, off otherwise) so existing EC2/RDS deploys keep working.
  ssl:
    process.env.DB_SSL === "false"
      ? false
      : config.isProduction
        ? { rejectUnauthorized: false }
        : false,
  synchronize: false,
  logging: config.env === "development",
  entities,
  migrations: [`${__dirname}/migrations/**/*.{ts,js}`],
});
